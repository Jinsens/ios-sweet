#!/usr/bin/env python3
"""Emit shim/diag.c's sentinel addresses for one embedded XNU payload.

    diag_syms.py KERNEL_MACHO PAYLOAD > shim/out/diag_syms.h

The shim copies payload segments to phys_base + (vmaddr - virt_base), so the
physical address of a kernel symbol is derived from the payload header, not
from the Mach-O file offset. Only symbols XNU writes very early are needed.
"""
import struct
import sys

LC_SEGMENT_64 = 0x19
LC_SYMTAB = 0x2


def macho_symbols(buf):
    magic, _, _, _, ncmds, _, _, _ = struct.unpack_from('<8I', buf, 0)
    assert magic == 0xfeedfacf, 'not a 64-bit Mach-O'
    symoff = nsyms = stroff = None
    off = 32
    for _ in range(ncmds):
        cmd, size = struct.unpack_from('<II', buf, off)
        if cmd == LC_SYMTAB:
            _, _, symoff, nsyms, stroff, _ = struct.unpack_from('<6I', buf, off)
        off += size
    if symoff is None:
        raise SystemExit('kernel has no LC_SYMTAB; cannot resolve sentinels')
    out = {}
    for i in range(nsyms):
        n_strx, n_type, _, _, n_value = struct.unpack_from('<IBBHQ', buf, symoff + 16 * i)
        end = buf.find(b'\0', stroff + n_strx)
        name = buf[stroff + n_strx:end].decode('utf-8', 'replace')
        if n_type & 0xe0:	# N_STAB
            continue
        out.setdefault(name, n_value)
    return out


def payload_header(path):
    buf = open(path, 'rb').read()
    if buf[:8] != b'SWEETXNU':
        raise SystemExit('payload has no SWEETXNU magic')
    virt_base, entry, _, _, _, phys_base, mem_size = struct.unpack_from('<7Q', buf, 0x10)
    return virt_base, entry, phys_base, mem_size


WANT = [
    ('XNU_DIAG_PA_BOOTSTRAP', '_bootstrap_pagetables'),
    ('XNU_DIAG_PA_BOOT_ARGS', '_const_boot_args'),
    ('XNU_DIAG_PA_GPHYS', '_gPhysBase'),
    ('XNU_DIAG_PA_GVIRT', '_gVirtBase'),
    ('XNU_DIAG_PA_LOWVEC', '_LowExceptionVectorBase'),
    ('XNU_DIAG_PA_ARM_INIT', '_arm_init'),
]


def main():
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    kernel = open(sys.argv[1], 'rb').read()
    syms = macho_symbols(kernel)
    virt_base, entry, phys_base, mem_size = payload_header(sys.argv[2])
    delta = phys_base - virt_base
    print('/* generated by tools/diag_syms.py: do not edit */')
    print('#define XNU_DIAG_VIRT_BASE 0x%xULL' % virt_base)
    print('#define XNU_DIAG_PHYS_BASE 0x%xULL' % phys_base)
    print('#define XNU_DIAG_MEM_SIZE 0x%xULL' % mem_size)
    print('#define XNU_DIAG_ENTRY_VA 0x%xULL' % entry)
    for macro, name in WANT:
        if name not in syms:
            raise SystemExit('missing symbol %s' % name)
        va = syms[name]
        if not virt_base <= va < virt_base + mem_size:
            raise SystemExit('%s is outside the copied kernel window' % name)
        print('#define %s 0x%xULL' % (macro, (va + delta) & 0xffffffffffffffff))


if __name__ == '__main__':
    main()
